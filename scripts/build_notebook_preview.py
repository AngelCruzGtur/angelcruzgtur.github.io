"""Regenerate the preview: pip install mistune pygments; python scripts/build_notebook_preview.py."""
import html
import json
import base64
import struct
from pathlib import Path

import mistune
from pygments import highlight
from pygments.formatters import HtmlFormatter
from pygments.lexers import PythonLexer

root = Path(__file__).resolve().parents[1]
notebook = json.loads((root / "notebooks/California_Wildfire_Risk.ipynb").read_text())
markdown = mistune.create_markdown(escape=True, plugins=["table", "url"])
parts = []
cell_number = 0
for cell in notebook["cells"]:
    source = "".join(cell["source"])
    if cell["cell_type"] == "markdown":
        parts.append('<div class="nb-markdown">' + markdown(source) + '</div>')
        continue
    if cell["cell_type"] != "code":
        continue
    is_heatmap = 'show_saved_map("hotspot_map_' in source
    cell_number += 1
    code = highlight(source, PythonLexer(), HtmlFormatter(nowrap=True))
    parts.append(f'<article class="nb-cell"><details class="nb-code">'
                 f'<summary><span class="nb-prompt">[{cell_number}]</span>'
                 '<span>Python code</span><span class="nb-chevron" aria-hidden="true">⌄</span></summary>'
                 '<pre><code>' + code + '</code></pre></details>')
    outputs = cell.get("outputs", [])
    if outputs:
        parts.append('<div class="nb-output"><span class="nb-output-label">Output</span>')
    for output in outputs:
        data = output.get("data", {})
        if "image/png" in data:
            image = "".join(data["image/png"])
            width, height = struct.unpack('>II', base64.b64decode(image)[16:24])
            chart_class = "nb-chart nb-heatmap" if is_heatmap else "nb-chart"
            alt = "Saved wildfire hotspot heat map" if is_heatmap else "Saved wildfire analysis chart"
            parts.append(f'<figure class="{chart_class}"><img width="{width}" height="{height}" loading="lazy" alt="{alt}" src="data:image/png;base64,'
                         + image.strip() + '"><figcaption><button type="button" aria-expanded="false" onclick="toggleNotebookChart(this)">Enlarge graph</button></figcaption></figure>')
        elif "text/html" in data:
            # Saved pandas tables generated by this repository's own notebook.
            table = "".join(data["text/html"])
            parts.append('<div class="notebook-table">' + table + "</div>")
        else:
            text = output.get("text", data.get("text/plain", ""))
            parts.append("<pre>" + html.escape("".join(text)) + "</pre>")
    if outputs:
        parts.append('</div>')
    parts.append('</article>')

preview = "\n".join(parts).replace('href="data/wildfire_weather_merged.csv"',
                                      'href="notebooks/data/wildfire_weather_merged.csv"')
(root / "notebooks/wildfire-preview.html").write_text(preview)
print("Built notebooks/wildfire-preview.html")
